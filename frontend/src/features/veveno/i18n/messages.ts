function invertKoErrorMessages(): Record<string, string> {
  const mapped: Record<string, string> = {};
  for (const [code, message] of Object.entries(VEVENO_KO.errors)) {
    if (code.startsWith('fail')) {
      continue;
    }
    mapped[message] = code;
  }
  return mapped;
}

